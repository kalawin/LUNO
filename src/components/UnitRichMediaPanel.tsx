// 🔊 ระบบอ่านออกเสียงภาษาไทยอัตโนมัติ (Web Speech API Thai Narrator)
// ============================================================================
function speakThaiText(text: string, onEnd?: () => void) {
  if (typeof window === 'undefined' || !('speechSynthesis' in window)) {
    if (onEnd) onEnd();
    return;
  }
  window.speechSynthesis.cancel();
  const cleanText = text.replace(/[•|→⇄✓✗🟢🟡🔴⚪]/gu, ' ').replace(/\s+/g, ' ').trim();
  const utter = new SpeechSynthesisUtterance(cleanText);
  utter.lang = 'th-TH';
  utter.rate = 1.02;
  const voices = window.speechSynthesis.getVoices();
  const thaiVoice = voices.find(v => v.lang.includes('th') || v.lang.includes('TH'));
  if (thaiVoice) utter.voice = thaiVoice;
  if (onEnd) {
    utter.onend = () => onEnd();
    utter.onerror = () => onEnd();
  }
  window.speechSynthesis.speak(utter);
}

function stopSpeakingThai() {
  if (typeof window !== 'undefined' && 'speechSynthesis' in window) {
    window.speechSynthesis.cancel();
  }
}

export const VoiceNarratorButton: React.FC<{ text: string; label?: string }> = ({
  text,
  label = 'ฟังเสียงสรุป'
}) => {
  const [speaking, setSpeaking] = useState(false);

  useEffect(() => {
    return () => stopSpeakingThai();
  }, []);

  const toggleSpeak = (e: React.MouseEvent) => {
    e.stopPropagation();
    if (speaking) {
      stopSpeakingThai();
      setSpeaking(false);
    } else {
      setSpeaking(true);
      speakThaiText(text, () => setSpeaking(false));
    }
  };

  return (
    <button
      type="button"
      onClick={toggleSpeak}
      style={{
        display: 'inline-flex',
        alignItems: 'center',
        gap: '6px',
        padding: '6px 12px',
        borderRadius: '999px',
        border: speaking ? '1.5px solid #0D9488' : '1px solid #CBD5E1',
        background: speaking ? '#CCFBF1' : '#FFFFFF',
        color: speaking ? '#0F766E' : '#334155',
        fontSize: '0.78rem',
        fontWeight: 700,
        cursor: 'pointer',
        transition: 'all 0.15s'
      }}
    >
      {speaking ? <VolumeX size={14} /> : <Volume2 size={14} />}
      <span>{speaking ? 'หยุดเสียงบรรยาย' : `🔊 ${label}`}</span>
    </button>
  );
};

