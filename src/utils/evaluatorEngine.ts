  // Fallback
  private static fallbackEval(unitId: string, data: Record<string, any>): UnitEvaluationResult {
    const keys = Object.keys(data).filter(k => !k.startsWith('ตรวจ_'));
    const filled = keys.filter(k => this.isMeaningfulText(String(data[k] || ''), 15)).length;
    const ratio = keys.length > 0 ? filled / keys.length : 0;
    const totalScore = Math.min(10, Math.max(2, Math.round(ratio * 10)));
    return {
      unitId,
      scores: { criterion1: Math.ceil(totalScore * 0.4), criterion2: Math.ceil(totalScore * 0.3), criterion3: Math.floor(totalScore * 0.3) },
      totalScore,
      maxPossible: 10,
      isPassed: totalScore >= 7,
      feedbacks: [
        {
          criterionId: 'fallback',
          title: 'การประเมินความครบถ้วนของชิ้นงาน',
          score: totalScore,
          maxScore: 10,
          status: totalScore >= 8 ? 'high' : totalScore >= 7 ? 'medium' : 'low',
          comment: totalScore >= 7 ? 'กรอกข้อมูลได้ครบถ้วนตามเกณฑ์มาตรฐาน' : 'ข้อมูลยังไม่สมบูรณ์ โปรดระบุรายละเอียดเพิ่มเติมในแบบฟอร์ม'
        }
      ]
    };
  }

  private static buildResult(
    unitId: string,
    items: { id: string; title: string; score: number; max: number; comment: string; sug?: string }[],
    rawData?: Record<string, any>
  ): UnitEvaluationResult {
    const copiedFields = rawData ? this.findCopiedSampleFields(unitId, rawData) : [];
    const hasCopiedSample = copiedFields.length > 0;

    const scores: Record<string, number> = {};
    let totalScore = 0;
    let maxPossible = 0;

    const feedbacks: CriterionFeedback[] = items.map(it => {
      // หากพบการคัดลอกตัวอย่าง ให้ปรับลดคะแนนเกณฑ์ละเหลือไม่เกิน 1 คะแนน เพื่อไม่ให้ผ่านเกณฑ์
      const effectiveItemScore = hasCopiedSample ? Math.min(1, it.score) : it.score;
      scores[it.id] = effectiveItemScore;
      totalScore += effectiveItemScore;
      maxPossible += it.max;
      const ratio = effectiveItemScore / it.max;
      const status: 'high' | 'medium' | 'low' = ratio >= 0.8 ? 'high' : ratio >= 0.5 ? 'medium' : 'low';
      return {
        criterionId: it.id,
        title: it.title,
        score: effectiveItemScore,
        maxScore: it.max,
        status,
        comment: hasCopiedSample
          ? `⚠️ ระบบตรวจพบการใช้ข้อความที่คัดลอกจากแนวทางหรือตัวอย่างต้นแบบ (ในช่อง: ${copiedFields.join(', ')}) ระบบจึงไม่อนุมัติคะแนนในส่วนนี้`
          : it.comment,
        suggestion: hasCopiedSample
          ? 'ห้ามคัดลอกคำตอบจากแนวทางหรือตัวอย่างต้นแบบ กรุณาเขียนคำตอบใหม่ด้วยสำนวนและบริบทจริงของสถานศึกษาท่านเอง'
          : it.sug
      };
    });

    return {
      unitId,
      scores,
      totalScore,
      maxPossible,
      isPassed: !hasCopiedSample && totalScore >= 7,
      hasCopiedSample,
      copiedFields,
      feedbacks
    };
  }
